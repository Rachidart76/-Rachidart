let activeType = "all";
let activeYear = "all";
let currentLanguage = localStorage.getItem("rachid-site-language") || "fr";

const root = document.documentElement;
const langSwitch = document.getElementById("langSwitch");
const yearFilter = document.getElementById("yearFilter");
const workCards = [...document.querySelectorAll(".work-card")];
const emptyState = document.getElementById("emptyState");
const dialog = document.getElementById("journeyDialog");

function applyLanguage(language) {
  const locale = translations[language];
  currentLanguage = language;
  root.lang = language === "ar" ? "ar" : "fr";
  root.dir = language === "ar" ? "rtl" : "ltr";
  document.title = language === "ar" ? "رشيد حداوي — فنان مغربي" : "Rachid Haddaoui — Artiste marocain";

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (locale[key]) element.innerHTML = locale[key];
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const key = element.dataset.i18nAlt;
    if (locale[key]) element.alt = locale[key];
  });

  langSwitch.querySelector(".lang-current").textContent = language === "ar" ? "ع" : "FR";
  langSwitch.querySelector(".lang-next").textContent = language === "ar" ? "FR" : "ع";
  langSwitch.setAttribute("aria-label", language === "ar" ? "Afficher le site en français" : "عرض الموقع بالعربية");
  localStorage.setItem("rachid-site-language", language);
}

function updateFilters() {
  let visibleCount = 0;
  workCards.forEach((card) => {
    const typeMatch = activeType === "all" || card.dataset.type === activeType;
    const yearMatch = activeYear === "all" || card.dataset.year === activeYear;
    const shouldShow = typeMatch && yearMatch;
    card.classList.toggle("is-hidden", !shouldShow);
    if (shouldShow) visibleCount += 1;
  });
  emptyState.hidden = visibleCount !== 0;
}

langSwitch.addEventListener("click", () => {
  applyLanguage(currentLanguage === "fr" ? "ar" : "fr");
});

document.querySelectorAll(".filter-chip").forEach((button) => {
  button.addEventListener("click", () => {
    document.querySelectorAll(".filter-chip").forEach((chip) => chip.classList.remove("active"));
    button.classList.add("active");
    activeType = button.dataset.filter;
    updateFilters();
  });
});

yearFilter.addEventListener("change", (event) => {
  activeYear = event.target.value;
  updateFilters();
});

document.querySelectorAll("[data-dialog]").forEach((button) => {
  button.addEventListener("click", () => dialog.showModal());
});

dialog.querySelector(".dialog-close").addEventListener("click", () => dialog.close());
dialog.addEventListener("click", (event) => {
  const rect = dialog.getBoundingClientRect();
  const clickedOutside = event.clientX < rect.left || event.clientX > rect.right || event.clientY < rect.top || event.clientY > rect.bottom;
  if (clickedOutside) dialog.close();
});

const revealObserver = new IntersectionObserver((entries) => {
  entries.forEach((entry) => {
    if (entry.isIntersecting) {
      entry.target.classList.add("visible");
      revealObserver.unobserve(entry.target);
    }
  });
}, { threshold: 0.12 });

document.querySelectorAll(".reveal").forEach((element) => revealObserver.observe(element));

const navLinks = [...document.querySelectorAll(".nav-links a")];
const sections = [...document.querySelectorAll("main > section")];

const sectionObserver = new IntersectionObserver((entries) => {
  entries.forEach((entry) => {
    if (entry.isIntersecting) {
      navLinks.forEach((link) => link.classList.toggle("active", link.getAttribute("href") === `#${entry.target.id}`));
    }
  });
}, { rootMargin: "-42% 0px -48%", threshold: 0 });

sections.forEach((section) => sectionObserver.observe(section));
document.getElementById("currentYear").textContent = new Date().getFullYear();
applyLanguage(currentLanguage);
